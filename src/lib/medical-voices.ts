export function filterMedicalVoices(
  voices: MedicalVoice[],
  options: { specialty?: string; query?: string },
) {
  const specialty = options.specialty?.trim();
  const query = options.query?.trim().toLowerCase();

  return voices.filter((voice) => {
    if (specialty && specialty !== "tutte" && !voice.specialtySlugs.includes(specialty)) {
      return false;
    }
    if (!query) return true;
    const haystack = [
      voice.name,
      voice.role,
      voice.institution,
      voice.city,
      voice.articleTitle,
      ...voice.specialtySlugs,
    ]
      .join(" ")
      .toLowerCase();
    return haystack.includes(query);
  });
}

export function medicalVoiceCities(voices: MedicalVoice[] = medicalVoices) {
  return [...new Set(voices.map((v) => v.city))].sort((a, b) => a.localeCompare(b, "it"));
}
